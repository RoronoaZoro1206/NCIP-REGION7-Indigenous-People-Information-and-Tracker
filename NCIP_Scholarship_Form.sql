CREATE TABLE SCHOLARSIP (
	SCHOLAR_CODE				SERIAL				PRIMARY KEY,
	SCHOLAR_NAME				VARCHAR(50)			NOT NULL,
	SCHOLAR_COURSE				VARCHAR(50),
	SCHOLAR_YEAR				SMALLINT,
